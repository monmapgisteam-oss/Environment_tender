/** Гэрээний хугацааг үе шат тус бүрт тэнцүү хуваарилна */
export function splitStages(companyId: string, start: string, end: string, names: string[]): Stage[] {
  const span = diffDays(end, start);
  const step = Math.max(1, Math.round(span / names.length));
  return names.map((name, i) => {
    const s = i === 0 ? start : addDays(start, step * i + 1);
    const e = i === names.length - 1 ? end : addDays(start, step * (i + 1));
    return {
      id: `${companyId}-s${i + 1}`,
      companyId,
      no: i + 1,
      name,
      short: name.length > 18 ? `${name.slice(0, 17)}…` : name,
      start: s,
      end: e,
    };
  });
}
